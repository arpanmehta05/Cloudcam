/** Cloud-provider display names (AWS/Azure/GCP) for a service href. */
function providerAliases(href: string): string[] {
  const serviceId = href.split("/").pop();
  const config = serviceId ? SERVICE_REGISTRY[serviceId] : undefined;
  if (!config) return [];
  return [
    config.displayName,
    config.azureDisplayName,
    config.gcpDisplayName,
  ].filter((name): name is string => Boolean(name));
}

