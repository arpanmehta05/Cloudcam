const allNavItems = navGroups.flatMap((group) =>
  group.items.map((item) => ({
    ...item,
    group: group.label,
    category: item.category || group.label,
    // System-admin-only items never surface to normal users in the service
    // directory or command palette.
    systemAdminOnly: item.systemAdminOnly,
    // Fold provider names (e.g. "Blob Storage" for S3) into aliases here so the
    // search engine stays a pure, registry-free ranker.
    aliases: [...(item.aliases || []), ...providerAliases(item.href)],
  })),
);

const seenHrefs = new Set<string>();
export const searchableNavItems = allNavItems.filter((item) => {
  if (seenHrefs.has(item.href)) return false;
  seenHrefs.add(item.href);
  return true;
});

export const serviceDirectoryItems = searchableNavItems;
